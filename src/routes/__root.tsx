import { useEffect, type ReactNode } from "react";

import appCss from "../styles.css?url";
import { reportLovableError } from "../lib/lovable-error-reporting";
import { AppShell } from "@/components/attend/AppShell";
import { Toaster } from "@/components/ui/sonner";
import { StoreProvider } from "@/lib/attend/store";
import { UiProvider } from "@/lib/attend/ui";
import { UpdateNotice } from "@/components/attend/UpdateNotice";

